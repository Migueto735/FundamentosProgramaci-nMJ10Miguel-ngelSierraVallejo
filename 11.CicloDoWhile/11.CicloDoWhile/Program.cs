using System;

namespace _11.CicloDoWhile
{
    internal class Program
    {
        static void Main(string[] args)
        {
            //Ciclo DoWhile
            int contador = 1;
            int acumulador = 0;

            do
            {
                acumulador += contador;
                contador++
            } while (contador < 0 5);

            Console.WriteLine($"La suma de los cinco primeros números enteros");
        }
    }
}
